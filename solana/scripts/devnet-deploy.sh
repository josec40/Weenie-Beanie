#!/usr/bin/env bash
# Deploys both programs to devnet and creates the mock USDC mint (6 decimals, mint authority = bank keypair).
# Prereqs: deployer ~/.config/solana/id.json funded with >= 4 devnet SOL (https://faucet.solana.com).
# Pool/config initialization (init_pool, init_config) is done by the backend in Phase 7.
set -euo pipefail

cd "$(dirname "$0")/.."
export PATH="$HOME/.local/share/solana/install/active_release/bin:$HOME/.cargo/bin:$HOME/.avm/bin:$PATH"
# Command Line Tools' linker cannot read the macOS 27 SDK yet; pin the newest SDK it can.
if [[ "$(uname)" == "Darwin" && -d /Library/Developer/CommandLineTools/SDKs/MacOSX26.5.sdk ]]; then
  export SDKROOT=/Library/Developer/CommandLineTools/SDKs/MacOSX26.5.sdk
fi

BANK_KEYPAIR="${BANK_KEYPAIR:-$HOME/.config/solana/shbean-bank.json}"
OUT_ENV="devnet.env"

solana config set --url devnet >/dev/null
balance=$(solana balance | awk '{print $1}')
if awk "BEGIN{exit !($balance < 4)}"; then
  echo "Deployer $(solana address) has $balance SOL; need >= 4 devnet SOL (https://faucet.solana.com)." >&2
  exit 1
fi

anchor build --arch v2
anchor deploy --provider.cluster devnet

if [[ ! -f "$BANK_KEYPAIR" ]]; then
  solana-keygen new --no-bip39-passphrase --silent -o "$BANK_KEYPAIR"
  chmod 600 "$BANK_KEYPAIR"
fi
BANK=$(solana-keygen pubkey "$BANK_KEYPAIR")
solana transfer --allow-unfunded-recipient "$BANK" 0.5 >/dev/null

if [[ -f "$OUT_ENV" ]] && grep -q '^MOCK_USDC_MINT=' "$OUT_ENV"; then
  MINT=$(grep '^MOCK_USDC_MINT=' "$OUT_ENV" | cut -d= -f2)
else
  MINT=$(spl-token create-token --decimals 6 --mint-authority "$BANK" --output json | python3 -c 'import json,sys; print(json.load(sys.stdin)["commandOutput"]["address"])')
fi

cat > "$OUT_ENV" <<EOF
# Non-secret devnet addresses (generated by scripts/devnet-deploy.sh)
SOLANA_CLUSTER=devnet
MICROLOAN_PROGRAM_ID=$(solana-keygen pubkey target/deploy/microloan-keypair.json)
REPUTATION_PROGRAM_ID=$(solana-keygen pubkey target/deploy/reputation-keypair.json)
BANK_AUTHORITY=$BANK
MOCK_USDC_MINT=$MINT
EOF
cat "$OUT_ENV"
echo "Bank keypair: $BANK_KEYPAIR (secret, never commit)"
